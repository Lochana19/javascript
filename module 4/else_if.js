// student mark grade list
// 90 to 100-A grade
// 70 to 89-B grade
// 50 to 69-C grade
// lower than 50
var stu_mark = 80


if(stu_mark>=90 & stu_mark<=100){
    console.log('Got A grade')
}

else if (stu_mark>=70 & stu_mark<=89){
    console.log("Got B grade")
}

else if(stu_mark>=50 & stu_mark<=69){
    console.log("Got C grade")
}

else {
    console.log("Very poor")
}




